(ns odradek.client
  "The Clojure client of Odradek, the server that owns an application's Kafka
  clients. Data in, data out:

      (require '[odradek.client :as odradek])

      (with-open [conn     (odradek/connect \"/var/run/kafka/kafka.sock\")
                  producer (odradek/producer conn)
                  consumer (odradek/consumer conn {:topics [\"orders.created\"]}
                                             (fn [record] (println (:offset record))))]
        @(odradek/send! producer {:topic \"orders.created\" :key \"42\" :value \"hello\"}))

  The application names topics only. Clusters, consumer groups, the stored
  format and encryption are the server's configuration.

  Records are maps. A key or a value is a byte array, a string (sent as UTF-8),
  a protobuf message, or nil. For a topic whose contract is a protobuf message
  type, give the producer and the consumer a codec for it under :contracts and
  pass and receive the records or maps protoc-gen-clojure generates:

      (def contracts
        {\"orders.created\"
         {:value (odradek/proto-codec orders/Order-prototype
                                      orders/Order->proto
                                      orders/proto->Order)}})

      (odradek/producer conn {:contracts contracts})
      (odradek/send! producer {:topic \"orders.created\" :value {:id \"42\" :total 100}})

  The protocol on top of the two gRPC streams (sequence numbers, the in-flight
  window, resends, credits, acknowledgements, the revoke handshake) is the
  Java core shared with the Java client. Needs Linux: the Unix socket uses
  Netty's epoll transport."
  (:require [clj-grpc.client :as grpc]
            [odradek.client.consumer :as consumer]
            [odradek.client.producer :as producer]
            [odradek.client.records :as records])
  (:import [io.grpc ManagedChannel]
           [java.lang AutoCloseable]
           [java.util.concurrent CompletableFuture Executors ScheduledExecutorService
            ThreadFactory TimeUnit]))

(set! *warn-on-reflection* true)

(deftype Connection [^ManagedChannel channel ^ScheduledExecutorService scheduler owned?]
  AutoCloseable
  (close [_]
    (.shutdownNow scheduler)
    (when owned?
      (.shutdownNow channel)
      (try
        (.awaitTermination channel 5 TimeUnit/SECONDS)
        (catch InterruptedException _
          (.interrupt (Thread/currentThread)))))
    nil))

(deftype Producer [state]
  AutoCloseable
  (close [_] (producer/close! state)))

(deftype Consumer [state]
  AutoCloseable
  (close [_] (consumer/close! state)))

(defn- scheduler
  ^ScheduledExecutorService []
  (Executors/newSingleThreadScheduledExecutor
   (reify ThreadFactory
     (newThread [_ runnable]
       (doto (Thread. runnable "odradek-client")
         (.setDaemon true))))))

(defn connect
  "Connects to the server's Unix domain socket and returns a connection, from
  which producers and consumers are made. Close it last, with `close!` or
  `with-open`.

  Nothing is dialled here: streams open when a producer or a consumer starts,
  and each reconnects for as long as it lives."
  ^Connection [socket-path]
  (Connection. (grpc/channel {:unix (str socket-path)} {}) (scheduler) true))

(defn connection
  "A connection over a gRPC channel the caller made and will shut down."
  ^Connection [^ManagedChannel channel]
  (Connection. channel (scheduler) false))

(defn proto-codec
  "The codec of a protobuf message type generated by protoc-gen-clojure, for
  :contracts: `prototype`, `->proto` and `proto->` are the three vars the
  generated namespace has for the type (X-prototype, X->proto, proto->X).
  Records and maps of the type are then encoded on the way out and decoded on
  the way in with clj-protobuf."
  [prototype ->proto proto->]
  (records/proto-codec prototype ->proto proto->))

(defn producer
  "Starts a producer. Options, all optional:

    :max-block-ms          how long `send!` waits when the window is full
                           (default 60000)
    :max-buffered-records  records held without a result before the server has
                           announced its window (default 1000)
    :max-buffered-bytes    the same limit in bytes (default 16 MiB)
    :contracts             {topic {:key codec, :value codec}}; see `proto-codec`.
                           A codec is {:encode (fn [value]) -> bytes,
                                       :decode (fn [bytes]) -> value}

  A producer survives the stream breaking: it reconnects and resends without
  duplicating, and fails a record as outcome unknown only when the server
  restarted before answering for it. Thread-safe."
  (^Producer [^Connection conn] (producer conn nil))
  (^Producer [^Connection conn options]
   (Producer. (producer/start (.-channel conn) (.-scheduler conn) options))))

(defn send!
  "Sends a record and returns a CompletableFuture of its outcome, so it can be
  dereferenced or composed. The future completes when every cluster the topic
  requires has acknowledged the record, never earlier. Records sent from one
  thread reach each partition in the order they were sent.

  The record is a map:

    :topic         required
    :key           bytes, string, protobuf message, a value of the topic's key
                   contract, or nil for a null key
    :value         the same; nil is a tombstone
    :headers       [{:key \"name\" :value bytes-or-string-or-nil} ...], in order
    :partition     chosen by the server's partitioner when absent
    :timestamp-ms  the server's clock when absent

  On success the future holds
    {:writes [{:cluster :topic :partition :offset :timestamp-ms} ...]}
  with one entry per cluster that wrote the record.

  On failure it completes exceptionally, so dereferencing throws an
  ExecutionException whose cause is an ex-info with this data:
    {:odradek/error     :produce-failed
     :code              the API's ErrorCode as a keyword, e.g.
                        :ERROR_CODE_TOPIC_NOT_CONFIGURED
     :message           for logs
     :kafka-exception   the Kafka exception's class name, or \"\"
     :outcome-unknown?  true when the record may have been written anyway
     :writes            the clusters that did write it}

  Blocks while the in-flight window is full, up to :max-block-ms, and then
  throws ex-info with :odradek/error :buffer-full. Also throws
  :record-too-large for a record that can never fit the window, :closed when
  the producer is closed or was refused by the server, and :cannot-encode for
  a key or value it has no encoding for."
  ^CompletableFuture [^Producer producer record]
  (producer/send! (.-state producer) record))

(defn consumer
  "Starts a consumer that calls `(handler record)` for each record, on one
  thread it owns. A record is marked as processed when the handler returns for
  it, and only processed records are committed. When the handler throws, the
  record is not processed, nothing after it is handed over, :on-failed gets the
  exception and the consumer stops; the record is delivered again to whoever
  reads the partition next.

  Options:

    :topics               required; they must share one cluster and group in
                          the server's configuration
    :max-processing-ms    longest the handler may hold a record (server default
                          when absent)
    :max-unacked-records  records the server may deliver ahead of the handler
                          (default 500)
    :contracts            {topic {:key codec, :value codec}}; see `producer`
    :on-assigned          (fn [partitions]) these partitions are now owned
    :on-revoked           (fn [partitions]) they are being taken away; when it
                          returns the server is told to proceed
    :on-lost              (fn [partitions]) they are gone without notice, as
                          when the stream breaks
    :on-failed            (fn [throwable]) the consumer stopped: the handler
                          threw, or the server refused the subscription
                          (ex-info with :odradek/error :consumer-failed and
                          :status-code)

  Partitions are [{:topic :partition} ...]. The callbacks run on the handler
  thread, in order with the records.

  The handler gets a map:

    {:topic :partition :offset :timestamp-ms
     :key      bytes, or decoded by the topic's key contract; nil for null
     :value    the same
     :headers  [{:key \"name\" :value bytes-or-nil} ...]}

  A record the server could not decode has :decode-error and its key, value
  and headers as stored in Kafka.

  A consumer survives the stream breaking: it reports its partitions lost,
  reconnects and resumes from the committed offsets."
  ^Consumer [^Connection conn options handler]
  (Consumer. (consumer/start (.-channel conn) (.-scheduler conn) options handler)))

(defn close!
  "Closes a producer, a consumer or a connection; `with-open` does the same.

  A producer stops taking records and waits up to a minute for the results of
  those already sent. A consumer stops after the record in progress, lets the
  server commit what was processed and leaves the group. Close producers and
  consumers before their connection."
  [^AutoCloseable closeable]
  (.close closeable))
