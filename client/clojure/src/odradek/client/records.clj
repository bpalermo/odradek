(ns odradek.client.records
  "The data an application exchanges with the client, to and from the API
  messages. The generated namespace does the field work; this adds what the
  application-facing shapes need on top. Not part of the public API."
  (:require [clj-protobuf.core :as pb]
            [odradek.kafka.v1.odradek :as api])
  (:import [com.google.protobuf MessageLite]
           [io.github.bpalermo.odradek.kafka.v1 ConsumedRecord ProduceRecord ProduceResult
            RecordBatch]
           [java.nio.charset StandardCharsets]))

(set! *warn-on-reflection* true)

(defn proto-codec
  "A codec for a protobuf message type generated by protoc-gen-clojure, from
  the three vars it emits for the type."
  [prototype ->proto proto->]
  {:encode (fn [value] (pb/encode (->proto value)))
   :decode (fn [^bytes bytes] (proto-> (pb/decode prototype bytes)))})

(defn- cannot-encode
  [what topic value]
  (ex-info (str "cannot encode the " (name what) " of a record for " topic ": "
                (.getName (class value))
                " is not bytes, a string or a protobuf message, and the topic has no contract"
                " for it")
           {:odradek/error :cannot-encode
            :topic topic
            :part what}))

(defn- ->bytes
  "The bytes of a key or a value. nil stays nil: a null key, or a tombstone."
  ^bytes [what topic codec value]
  (cond
    (nil? value) nil
    (bytes? value) value
    (string? value) (.getBytes ^String value StandardCharsets/UTF_8)
    (instance? MessageLite value) (.toByteArray ^MessageLite value)
    (:encode codec) ((:encode codec) value)
    :else (throw (cannot-encode what topic value))))

(defn- header
  [topic {:keys [key value]}]
  {:key key
   :value (->bytes :header topic nil value)})

(defn produce-record
  "The API message for a record map. `contracts` maps a topic to the codecs of
  its key and value."
  ^ProduceRecord [contracts {:keys [topic key value headers partition timestamp-ms]}]
  (when-not (string? topic)
    (throw (ex-info "a record needs a :topic" {:odradek/error :invalid-record})))
  (let [contract (get contracts topic)]
    (api/ProduceRecord->proto
     {:topic topic
      :partition partition
      :key (->bytes :key topic (:key contract) key)
      :value (->bytes :value topic (:value contract) value)
      :headers (mapv #(header topic %) headers)
      :timestamp-ms timestamp-ms})))

(defn partition-of
  "The application's name for a partition."
  [topic partition]
  {:topic topic :partition (long partition)})

(defn- decode
  [codec bytes]
  (if (and bytes (:decode codec))
    ((:decode codec) bytes)
    bytes))

(defn received
  "The record map a handler gets. A record the server could not decode comes
  as it is stored in Kafka, with :decode-error, and is not decoded here either."
  [contracts ^RecordBatch batch ^ConsumedRecord record]
  (let [topic (.getTopic batch)
        {:keys [key value headers decode-error]} (api/proto->ConsumedRecord record)
        contract (when-not decode-error (get contracts topic))]
    (cond-> {:topic topic
             :partition (long (.getPartition batch))
             :offset (.getOffset record)
             :timestamp-ms (.getTimestampMs record)
             :key (decode (:key contract) key)
             :value (decode (:value contract) value)
             :headers (mapv (fn [h] {:key (:key h) :value (:value h)}) headers)}
      decode-error (assoc :decode-error decode-error))))

(defn- write
  [{:keys [cluster topic partition offset timestamp-ms]}]
  {:cluster cluster
   :topic topic
   :partition (long (or partition 0))
   :offset (long (or offset 0))
   :timestamp-ms (long (or timestamp-ms 0))})

(def ^:private outcome-unknown?
  #{:ERROR_CODE_OUTCOME_UNKNOWN :ERROR_CODE_INTERNAL})

(defn send-outcome
  "What a send resolves to: {:writes [...]} when every required cluster
  acknowledged, otherwise an exception whose data says why and which clusters
  hold the record anyway."
  [^ProduceResult result]
  (let [{:keys [error writes]} (api/proto->ProduceResult result)
        writes (mapv write writes)]
    (if error
      (let [code (or (:code error) :ERROR_CODE_UNSPECIFIED)]
        (ex-info (str (name code) ": " (:message error))
                 {:odradek/error :produce-failed
                  :code code
                  :message (or (:message error) "")
                  :kafka-exception (or (:kafka-exception error) "")
                  :outcome-unknown? (contains? outcome-unknown? code)
                  :writes writes}))
      {:writes writes})))
